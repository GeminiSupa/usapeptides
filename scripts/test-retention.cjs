const ts = require('typescript');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const compiled = ts.transpileModule(fs.readFileSync('src/lib/retention.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const mod = { exports: {} };
new Function('exports', 'module', compiled)(mod.exports, mod);
const { reorderEstimate: estimate, PAID_ORDER_STATUSES: paid } = mod.exports;
const now = Date.parse('2026-02-01');
assert.equal(estimate(['2026-01-01', '2026-01-15'], null, now), null);
assert.equal(estimate(['2026-01-01', '2026-01-01', '2026-01-15'], null, now), null);
const regular = estimate(['2026-01-01', '2026-01-15', '2026-01-29'], null, now);
assert.equal(regular.intervalDays, 14);
assert.equal(regular.dueAt, '2026-02-12');
assert.equal(regular.status, 'Upcoming');
assert.equal(estimate(['2026-01-01'], 14, now).status, 'Overdue');
assert.equal(estimate([], 14, now), null);
assert.equal(estimate(['2026-01-01'], 31, now).daysUntil, 0);
assert.equal(paid.has('pending'), false);
assert.equal(paid.has('refunded'), false);
assert.equal(paid.has('completed'), true);
console.log('Retention tests passed: sparse history, split orders, cadence, overrides, due dates and paid status.');
